function finDeChaine(source: string, ouverture: number): number {
  for (let index = ouverture + 1; index < source.length; index += 1) {
    if (source[index] === "\\") index += 1
    else if (source[index] === source[ouverture]) return index
  }
  return source.length
}

function finDeBloc(source: string, ouverture: number): number {
  let profondeur = 0
  for (let index = ouverture; index < source.length; index += 1) {
    const caractere = source[index]
    if (caractere === '"' || caractere === "'" || caractere === "`") {
      index = finDeChaine(source, index)
      continue
    }
    if (caractere === "{") profondeur += 1
    else if (caractere === "}" && --profondeur === 0) return index
  }
  return -1
}

const TETE =
  /^(?:\s|\/\/[^\n]*|\/\*[\s\S]*?\*\/)*(?:export\s+(?:default\s+)?)?(?:async\s+)?(?:function\s*\*?\s*([A-Za-z_$][\w$]*)|(?:const|let|var)\s+([A-Za-z_$][\w$]*)|class\s+([A-Za-z_$][\w$]*))/

function declarationsDePremierNiveau(
  source: string
): { debut: number; nom: string }[] {
  const trouvees: { debut: number; nom: string }[] = []
  let profondeur = 0
  let debut = 0
  let index = 0
  while (index < source.length) {
    const caractere = source[index]
    if (caractere === '"' || caractere === "'" || caractere === "`") {
      index = finDeChaine(source, index) + 1
      continue
    }
    if (caractere === "/" && source[index + 1] === "/") {
      const saut = source.indexOf("\n", index)
      if (saut < 0) break
      index = saut + 1
      continue
    }
    if (caractere === "/" && source[index + 1] === "*") {
      const fin = source.indexOf("*/", index)
      if (fin < 0) break
      index = fin + 2
      continue
    }
    if (caractere === "{" || caractere === "(" || caractere === "[") {
      profondeur += 1
    } else if (caractere === "}" || caractere === ")" || caractere === "]") {
      profondeur = Math.max(0, profondeur - 1)
    } else if (caractere === "\n" && profondeur === 0) {
      const nom = nomDeTete(source.slice(debut, index))
      if (nom) trouvees.push({ debut, nom })
      debut = index + 1
    }
    index += 1
  }
  const nom = nomDeTete(source.slice(debut))
  if (nom) trouvees.push({ debut, nom })
  return trouvees
}

function nomDeTete(statement: string): string | undefined {
  return statement
    .match(TETE)
    ?.slice(1)
    .find((groupe) => groupe !== undefined)
}

function declarationDe(
  declarations: readonly { debut: number; nom: string }[],
  index: number
): string {
  let nom = RACINE
  for (const declaration of declarations) {
    if (declaration.debut > index) break
    nom = declaration.nom
  }
  return nom
}

function nomsLiesAuDelegue(source: string, delegue: string): string[] {
  const noms = new Set<string>()
  const propriete = `(?:\\??\\.\\s*${delegue}\\b|\\??\\.?\\s*\\[\\s*["'\`]${delegue}["'\`]\\s*\\])`

  for (const entree of source.matchAll(
    new RegExp(
      `\\b(?:const|let|var)\\s*\\{([^{}]*)\\}[ \\t]*=[ \\t]*[^\\n]*$`,
      "gm"
    )
  )) {
    for (const morceau of (entree[1] ?? "").split(",")) {
      const morceaux = morceau.split(":")
      const lu = (morceaux[0] ?? "").split("=")[0]!.trim()
      const lie = (
        morceaux.length > 1 ? morceaux.slice(1).join(":") : morceaux[0]!
      )
        .split("=")[0]!
        .trim()
      if (lu === delegue && /^[A-Za-z_$][\w$]*$/.test(lie)) noms.add(lie)
    }
  }

  for (const entree of source.matchAll(
    new RegExp(
      `\\b(?:const|let|var)\\s+([A-Za-z_$][\\w$]*)[ \\t]*(?::[^=\\n]*)?=[ \\t]*[^=;\\n]*?${propriete}[ \\t]*$`,
      "gm"
    )
  )) {
    noms.add(entree[1]!)
  }

  return [...noms]
}

function reperesDeDelegue(
  source: string,
  delegue: string
): Omit<Repere, "voie">[] {
  const portee = `(?:[A-Za-z_$][\\w$]*\\s*\\??\\.\\s*${delegue}|[A-Za-z_$][\\w$]*\\s*\\??\\.?\\s*\\[\\s*["'\`]${delegue}["'\`]\\s*\\])`
  const lies = nomsLiesAuDelegue(source, delegue)
  const motifs: { motif: RegExp; portee: boolean }[] = [
    {
      motif: new RegExp(
        `${portee}\\s*\\??\\.\\s*([A-Za-z_$][\\w$]*)\\s*(?:\\?\\.)?\\s*\\(`,
        "g"
      ),
      portee: true,
    },
    ...(lies.length === 0
      ? []
      : [
          {
            motif: new RegExp(
              `(?:^|[^A-Za-z_$0-9.])\\b(${lies.join("|")})\\s*\\??\\.\\s*([A-Za-z_$][\\w$]*)\\s*(?:\\?\\.)?\\s*\\(`,
              "g"
            ),
            portee: false,
          },
        ]),
  ]

  const vus = new Map<number, { delegation: string; extrait: string }>()
  for (const { motif, portee: parPortee } of motifs) {
    for (const entree of source.matchAll(motif)) {
      const delegation = entree[1]!
      if (ECRITURES_DELEGUEES.has(delegation)) continue
      const extrait = parPortee
        ? entree[0].replace(/\s*(?:\?\.)?\s*\($/, "").replace(/^[^\S\n]+/, "")
        : `${entree[1]}.${entree[2]}`
      vus.set(entree.index ?? 0, {
        delegation: parPortee ? delegation : entree[2]!,
        extrait,
      })
    }
  }

  return [...vus].map(([index, { delegation, extrait }]) => ({
    index,
    delegation,
    extrait,
  }))
}

function reperesDeRelation(
  source: string,
  champ: string
): Omit<Repere, "voie" | "delegation">[] {
  const vus = new Map<number, string>()
  for (const entree of source.matchAll(/\b(include|select)\s*:\s*\{/g)) {
    const ouverture = (entree.index ?? 0) + entree[0].length - 1
    const fin = finDeBloc(source, ouverture)
    if (fin < 0) continue
    for (const cle of source
      .slice(ouverture, fin + 1)
      .matchAll(new RegExp(`\\b${champ}\\b["'\`]?\\s*(?=[,:}])`, "g"))) {
      vus.set(ouverture + (cle.index ?? 0), `${entree[1]}: ${champ}`)
    }
  }
  return [...vus].map(([index, extrait]) => ({ index, extrait }))
}

export function estGeneree(chemin: string): boolean {
  return chemin.startsWith(ARBORESCENCE_GENEREE)
}

export function sitesDeLecture(
  sources: readonly SourceProduction[],
  forme: FormeDeLaStructure
): SiteLecture[] {
  return sources
    .filter(({ chemin }) => !estGeneree(chemin))
    .flatMap(({ chemin, source }) => {
      const declarations = declarationsDePremierNiveau(source)
      return [
        ...reperesDeDelegue(source, forme.delegue).map((repere) => ({
          ...repere,
          voie: "delegue" as const,
        })),
        ...reperesDeRelation(source, forme.champ).map(({ index, extrait }) => ({
          index,
          voie: "relation" as const,
          delegation: null,
          extrait,
        })),
      ]
        .sort((a, b) => a.index - b.index)
        .map(({ index, voie, delegation, extrait }) => ({
          chemin,
          ligne: source.slice(0, index).split("\n").length,
          voie,
          delegation,
          extrait,
          declaration: declarationDe(declarations, index),
        }))
    })
    .sort((a, b) => a.chemin.localeCompare(b.chemin) || a.ligne - b.ligne)
}
